test('browser: invited passkey enrollment, backup, reauthentication, reload and login on desktop/mobile', { timeout: 90000 }, async t => {
    const fixture = await authFixture(t);
    const browser = await chromium.launch({ channel: 'chromium', headless: true });
    t.after(() => browser.close());
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const cdp = await page.context().newCDPSession(page);
    await cdp.send('WebAuthn.enable');
    const virtual = () => cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
    const main = await virtual();
    const screenshots = await mkdtemp(join(tmpdir(), 'kp-passkey-browser-'));
    await page.goto(fixture.origin);
    await expect(page.getByRole('button', { name: 'パスキーでログイン' })).toBeVisible();
    await page.screenshot({ path: join(screenshots, 'desktop-login.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: join(screenshots, 'mobile-login.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const invitation = await fixture.issue();
    await page.goto(`${fixture.origin}/#enroll=${invitation.token}`);
    await page.reload();
    await expect(page.getByRole('button', { name: 'パスキーを登録', exact: true })).toBeVisible();
    assert.equal(new URL(page.url()).hash, '');
    const registrationOptions = page.waitForResponse(response => response.url().endsWith('/api/auth/register/options'));
    await page.getByRole('button', { name: 'パスキーを登録', exact: true }).click();
    assert.equal((await (await registrationOptions).json()).options.user.name, 'person@abist.co.jp');
    await expect(page.getByRole('heading', { name: 'ホーム', exact: true })).toBeVisible();
    assert.equal(await page.evaluate(() => sessionStorage.getItem('app-token')), null);
    assert.equal(await page.evaluate(() => sessionStorage.getItem('demo-token')), null);
    assert.equal(await page.evaluate(() => document.cookie.includes('kp-session')), false);
    const cookies = await page.context().cookies();
    assert.ok(cookies.some(cookie => cookie.name === 'kp-session' && cookie.httpOnly && cookie.sameSite === 'Lax'));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '管理・セキュリティ', exact: true }).click();
    await expect(page.getByText('メインキー', { exact: true })).toBeVisible();
    await cdp.send('WebAuthn.removeVirtualAuthenticator', { authenticatorId: main.authenticatorId });
    await virtual();
    await page.getByRole('button', { name: '予備キーを追加', exact: true }).click();
    await expect(page.getByText('予備キー', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '本人確認', exact: true }).click();
    await expect(page.getByText('本人確認が完了しました')).toBeVisible();
    await page.screenshot({ path: join(screenshots, 'desktop-settings.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.locator('.sidebar')).not.toBeInViewport();
    await page.screenshot({ path: join(screenshots, 'mobile-settings.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.reload();
    await expect(page.getByRole('heading', { name: 'ホーム', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'メニュー', exact: true }).click();
    await page.getByRole('button', { name: /ログアウト/ }).click();
    await expect(page.getByRole('button', { name: 'パスキーでログイン' })).toBeVisible();
    await page.getByRole('button', { name: 'パスキーでログイン' }).click();
    await expect(page.getByRole('heading', { name: 'ホーム', exact: true })).toBeVisible();
    assert.deepEqual(errors, []);
    console.log(`Browser screenshots: ${screenshots}`);
});

